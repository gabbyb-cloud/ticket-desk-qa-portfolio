import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { parseDocument } from 'yaml';

const text = readFileSync('.github/workflows/ci.yml', 'utf8');
const document = parseDocument(text, { uniqueKeys: true });
if (document.errors.length) throw new Error('Workflow YAML parsing failed.');
const workflow = document.toJS();
const check = (value, message) => { if (!value) throw new Error(message); };
check(Object.keys(workflow.on).sort().join(',') === 'pull_request,push', 'Unsafe or unexpected trigger.');
check(JSON.stringify(workflow.permissions) === JSON.stringify({ contents: 'read' }), 'Workflow permissions exceed read.');
check(Object.keys(workflow.jobs).length === 1, 'Only one QA job is authorized.');
const job = workflow.jobs.qa;
check(job['runs-on'] === 'windows-2025', 'Windows runner required.');
check(job['timeout-minutes'] === 20, 'Job timeout missing.');
const approvedActions = ["actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1","actions/setup-node@949feb2413d6458794dcd2491c4babbbce0c15c1","actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9"];
const actions = job.steps.filter(step => step.uses);
check(actions.length === 3, 'Unexpected action count.');
for (const step of actions) check(approvedActions.includes(step.uses), 'Action differs from approved SHA pins.');
check(job.steps[0].with['persist-credentials'] === false, 'Checkout must not persist credentials.');
const upload = actions.find(step => step.uses.startsWith('actions/upload-artifact@'));
check(upload.if === 'failure()', 'Upload must be failure-only.');
check(upload.with['retention-days'] === 7 && upload.with['include-hidden-files'] === false, 'Artifact retention/visibility mismatch.');
const expected = ['qa-reports/checks.json', 'qa-reports/qa.json', 'qa-reports/qa.html', 'qa-reports/qa.xml'];
check(JSON.stringify(upload.with.path.trim().split(/\s+/)) === JSON.stringify(expected), 'Artifact allowlist changed.');
check(job.steps.some(step => step.run === 'npm.cmd ci --ignore-scripts --no-audit --no-fund'), 'Locked install missing.');
check(job.steps.some(step => step.run === 'node scripts/run-tests.mjs --workers=2 --stage-ci'), 'Safe zero-retry test runner missing.');
const testConfig = readFileSync('playwright.config.ts', 'utf8');
check(/retries:\s*0/.test(testConfig) && /trace:\s*'off'/.test(testConfig) && /screenshot:\s*'off'/.test(testConfig) && /video:\s*'off'/.test(testConfig), 'Unsafe browser artifact or retry configuration.');
mkdirSync('docs/evidence/phase-3', { recursive: true });
writeFileSync('docs/evidence/phase-3/workflow-validation.json', JSON.stringify({ checkedAtUtc: new Date().toISOString(), command: 'node scripts/validate-workflow.mjs', yamlParsed: true, policyChecksPassed: true, workflowSha256: createHash('sha256').update(text).digest('hex'), githubExecutionVerified: false, limitations: 'YAML parsing and focused local policy checks; not the GitHub service validator or an executed hosted workflow.' }, null, 2) + '\n');
console.log('Workflow YAML and local policy checks passed; GitHub execution remains unverified.');
